"""Generated model documents: error analysis and the model card.

Both are rebuilt from committed artifacts (``artifacts/evals/<rung>/`` and
the label tables), so the numbers in the documents always match the files.
"""

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from hotel_curator.taxonomy import LABELS

EXAMPLES_PER_KIND = 3
MAX_TEXT = 160


def _short(text: str) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= MAX_TEXT else text[: MAX_TEXT - 3] + "..."


def error_table(
    gold: pd.DataFrame, scores: pd.DataFrame, thresholds: dict[str, float]
) -> pd.DataFrame:
    """Part-level gold, prediction and score for every label, long format."""
    merged = gold.merge(
        scores, on=["review_id", "part"], suffixes=("", "_score")
    )
    rows = []
    for label in LABELS:
        score = merged[f"{label}_score"].to_numpy()
        rows.append(
            pd.DataFrame(
                {
                    "label": label,
                    "review_id": merged["review_id"],
                    "part": merged["part"],
                    "text": merged["text"],
                    "gold": merged[label].to_numpy(dtype=bool),
                    "pred": score >= thresholds[label],
                    "score": score,
                }
            )
        )
    return pd.concat(rows, ignore_index=True)


def errors_markdown(name: str, table: pd.DataFrame) -> str:
    """Per-label false positives and false negatives with examples.

    Examples are the most confident mistakes (highest-scoring false
    positives, lowest-scoring false negatives), which are the most useful
    to read: they show systematic confusions rather than borderline calls.
    """
    lines = [
        f"# Error analysis: `{name}` on gold-test",
        "",
        "_Generated by `curator model report`. Part-level, at the gold-dev "
        "thresholds. Texts are review parts as published (punctuation "
        "removed by the data publisher)._",
        "",
        "| Label | Support | False positives | False negatives |",
        "|---|---:|---:|---:|",
    ]
    for label in LABELS:
        sub = table[table["label"] == label]
        fp = int((sub["pred"] & ~sub["gold"]).sum())
        fn = int((~sub["pred"] & sub["gold"]).sum())
        lines.append(f"| {label} | {int(sub['gold'].sum())} | {fp} | {fn} |")
    lines.append("")
    for label in LABELS:
        sub = table[table["label"] == label]
        fps = sub[sub["pred"] & ~sub["gold"]].nlargest(
            EXAMPLES_PER_KIND, "score"
        )
        fns = sub[~sub["pred"] & sub["gold"]].nsmallest(
            EXAMPLES_PER_KIND, "score"
        )
        if fps.empty and fns.empty:
            continue
        lines += [f"## {label}", ""]
        for kind, rows in (("False positive", fps), ("False negative", fns)):
            for _, row in rows.iterrows():
                lines.append(
                    f"- {kind} (score {row['score']:.2f}, "
                    f'{row["part"]}): "{_short(row["text"])}"'
                )
        lines.append("")
    return "\n".join(lines)


def _fmt_ci(ci: dict[str, float]) -> str:
    return f"{ci['point']:.3f} [{ci['low']:.3f}, {ci['high']:.3f}]"


@dataclass(frozen=True)
class CardInputs:
    """The committed artifacts a model card is built from."""

    name: str
    report: dict[str, Any]
    package_report: dict[str, Any] | None
    throughput: dict[str, Any] | None
    provenance: dict[str, Any] | None
    promotion: dict[str, Any]


def _card_intro(c: CardInputs) -> list[str]:
    return [
        f"# Model card: `{c.name}`",
        "",
        "_Generated by `curator model report` from committed evaluation "
        "artifacts._",
        "",
        "## What it does",
        "",
        "Labels one part of a hotel review (the guest's *Liked* or *Disliked* "
        "text) with any of 16 labels: eight hotel attributes (cleanliness, "
        "room, staff, location, noise, wifi, value, breakfast & food) times "
        "praise or complaint. Hotel tiers are computed from these labels' "
        "calibrated probabilities (ADR 006).",
        "",
        "**Intended use:** aggregate statements about hotels from many "
        "reviews, with uncertainty. **Not for:** judging a single review "
        "or a single guest, moderating content, or any decision about "
        "people.",
        "",
    ]


def _card_training(c: CardInputs) -> list[str]:
    params = c.report["params"]
    base = f"- Base model: `{params.get('base_model')}`"
    if c.provenance:
        base += (
            f" ({c.provenance.get('title')}; licence: "
            f"{c.provenance.get('license')}; source: "
            f"{c.provenance.get('provenance')})"
        )
    minutes = c.report["summary"].get("seconds_train", float("nan")) / 60
    return [
        "## Training",
        "",
        base,
        f"- Training data: {params.get('n_train_parts')} review parts from "
        f"{params.get('n_train_reviews')} reviews of "
        f"{params.get('n_train_hotels')} training-split hotels "
        f"(label sets: {params.get('train_sets')}), labelled by one LLM "
        "annotator under guideline v2.0 (ADR 004, "
        "`docs/labeling/GUIDELINES.md`).",
        f"- Hyperparameters: learning rate {params.get('learning_rate')}, "
        f"batch {params.get('batch_size')}, {params.get('epochs')} epochs "
        f"(best: {params.get('best_epoch')}), max length "
        f"{params.get('max_length')}, warmup {params.get('warmup_ratio')}, "
        f"weight decay {params.get('weight_decay')}, positive-weight cap "
        f"{params.get('pos_weight_cap')}, seed {params.get('seed')}.",
        f"- Training time on 4 CPU cores: {minutes:.0f} minutes.",
        "- Epoch selection: gold-dev macro-F1 at thresholds tuned on gold-dev.",
        "",
        "| Epoch | Train loss | Gold-dev part macro-F1 |",
        "|---:|---:|---:|",
        *[
            f"| {h['epoch']} | {h['train_loss']:.4f} | "
            f"{h['dev_macro_f1']:.4f} |"
            for h in params.get("history", [])
        ],
        "",
    ]


def _card_evaluation(c: CardInputs) -> list[str]:
    test, dev = c.report["test"], c.report["dev"]
    rows = {r["name"]: r for r in c.promotion["rows"]}
    diff = rows[c.name]["vs_v1"]
    v1 = c.promotion["v1_config"]
    v1s = rows[v1]["summary"]
    ece = np.mean(list(test["review_ece"].values()))
    return [
        "## Evaluation (gold-test: 1,200 reviews, 182 hotels never seen)",
        "",
        "Gold labels are the majority of three LLM annotators; their agreement "
        "with human annotators on an external set is reported in "
        "`docs/labeling/EXTERNAL_CHECK.md`.",
        "",
        "| Metric | Value [95% CI] |",
        "|---|---|",
        f"| Review-level macro-F1 | {_fmt_ci(test['review_macro_f1'])} |",
        f"| v1 checkpoint (best configuration, `{v1}`) | "
        f"{v1s['test_review_macro_f1']:.3f} "
        f"[{v1s['test_review_macro_f1_low']:.3f}, "
        f"{v1s['test_review_macro_f1_high']:.3f}] |",
        f"| Difference vs v1 (paired, hotel clusters) | "
        f"{diff['point']:+.3f} [{diff['low']:+.3f}, {diff['high']:+.3f}] |",
        f"| Review-level micro-F1 | {test['review_micro_f1']:.3f} |",
        f"| Part-level macro-F1 | {_fmt_ci(test['part_macro_f1'])} |",
        f"| Mean review-level ECE (calibrated) | {ece:.4f} |",
        f"| Review-level Brier score | {test['review_brier']:.4f} |",
        "| Cross-polarity F1 (complaints in Liked, praise in Disliked) | "
        f"{test['cross_polarity']['f1']:.3f} "
        f"(support {test['cross_polarity']['support']:.0f}) |",
        "| Gold-dev review-level macro-F1 (selection) | "
        f"{dev['review_macro_f1']['point']:.3f} |",
        "",
        "Per-label scores, slices and calibration tables: "
        "`docs/model/COMPARISON.md`. Typical mistakes: `docs/model/ERRORS.md`.",
        "",
    ]


def _card_package(c: CardInputs) -> list[str]:
    if not c.package_report:
        return []
    report = c.package_report
    pdev = report["dev_review_macro_f1"]
    test = report["gold_test"]
    ece = sum(test["review_ece"].values()) / len(test["review_ece"])
    tolerance = report.get("max_quantization_loss", "a fixed tolerance")
    lines = [
        "## Served package",
        "",
        f"- Format: ONNX, {report['weights']} weights. Gold-dev "
        f"review macro-F1 fp32 {pdev['fp32']:.4f}, int8 {pdev['int8']:.4f} "
        f"(int8 is shipped when it loses at most {tolerance}).",
        "- Packaged model on gold-test: review-level macro-F1 "
        f"{_fmt_ci(test['review_macro_f1'])}, mean review-level ECE "
        f"{ece:.4f}. Promotion re-checks rules 1 and 3 on these scores.",
    ]
    if c.throughput:
        t = c.throughput
        lines.append(
            f"- Throughput on {t.get('threads', 4):.0f} CPU threads (median "
            f"of {t.get('repeats', 1):.0f} timed passes): "
            f"{t['parts_per_second']:.0f} "
            f"parts/s on a {t['sample_parts']:.0f}-part corpus sample; the "
            f"{t['corpus_parts']:,.0f}-part corpus takes about "
            f"{t['corpus_hours']:.2f} hours."
        )
    return [*lines, ""]


LIMITS = [
    "## Limits and known failure modes",
    "",
    "- Labels are machine-made (an LLM panel), not human gold; the panel "
    "marks more mild complaints than the human annotators of an external "
    "set did (`docs/labeling/EXTERNAL_CHECK.md`).",
    "- English reviews from European city hotels on one booking site, "
    "2015-2017; other sites, languages, regions or years are untested.",
    "- The publisher removed punctuation, so sentence boundaries and "
    "negation scope are harder; see the cross-polarity row above.",
    "- The comparison with modern encoders is partial: huggingface.co was "
    "blocked during the build (`docs/BLOCKERS.md` B1), so the only "
    "ModernBERT-architecture model tried was mmBERT-small; ModernBERT-base, "
    "DeBERTa-v3 and Ettin were not trained (ADR 005).",
]
RARE_LABELS = 3
WEAKEST_LABELS = 4


def _label_limits(c: CardInputs) -> list[str]:
    """The labels with the least gold-test support and the lowest F1."""
    rows = c.report["test"]["per_label"]
    rare = sorted(rows, key=lambda r: r["support"])[:RARE_LABELS]
    weak = sorted(rows, key=lambda r: r["f1"])[:WEAKEST_LABELS]
    return [
        "- Fewest gold-test examples: "
        + ", ".join(f"{r['label']} ({r['support']} reviews)" for r in rare)
        + "; lowest F1: "
        + ", ".join(f"{r['label']} ({r['f1']:.3f})" for r in weak)
        + ". Per-label scores: `docs/model/COMPARISON.md`.",
        "",
    ]


def model_card(inputs: CardInputs) -> str:
    """``MODEL_CARD.md`` for a packaged model."""
    sections = (
        _card_intro,
        _card_training,
        _card_evaluation,
        _card_package,
        lambda c: LIMITS,
        _label_limits,
    )
    lines = [line for make in sections for line in make(inputs)]
    return "\n".join(lines)


def load_json(path: Path) -> dict[str, Any] | None:
    """Parse ``path`` if it exists."""
    return json.loads(path.read_text()) if path.is_file() else None
