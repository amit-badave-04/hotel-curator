"""``curator label``: draw annotation samples and merge panel answers."""

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Annotated, Any

import pandas as pd
import typer

from hotel_curator.config import get_settings
from hotel_curator.taxonomy import LABELS

app = typer.Typer(help="Annotation samples, panel answers and gold sets.")


@dataclass(frozen=True)
class SetPlan:
    """Size and source split of one annotation set."""

    name: str
    split: str
    n_total: int
    seed_offset: int


SET_PLANS = (
    SetPlan("gold_test", "test", 1200, 1),
    SetPlan("gold_dev", "val", 600, 2),
    SetPlan("train", "train", 4000, 3),
)
ENRICHED_SHARE = 0.3
EXTRA_TRAIN = SetPlan("train_2", "train", 4000, 4)
"""Second training sample, drawn because the learning curve on the first
4,000 reviews had not flattened (plan section 3.2)."""


Force = Annotated[
    bool,
    typer.Option(
        help="Redraw a set that already exists. Its answers then no longer "
        "match its reviews."
    ),
]


def _refuse_redraw(labels_dir: Path, names: list[str], force: bool) -> None:
    """Stop before a committed sample is replaced by accident.

    A redraw on today's tables would not reproduce a set drawn before a
    data change, and would orphan the panel answers collected for it.
    """
    existing = [n for n in names if (labels_dir / n / "index.json").is_file()]
    if existing and not force:
        raise typer.BadParameter(
            f"{existing} already drawn; pass --force to redraw"
        )


@app.command("sample")
def sample_cmd(
    batch_size: int = typer.Option(100, help="Reviews per annotator prompt."),
    force: Force = False,
) -> None:
    """Draw the gold-test, gold-dev and train samples and write prompts."""
    from hotel_curator.labeling.batches import write_set
    from hotel_curator.labeling.prompt import load_guideline
    from hotel_curator.labeling.sampling import SampleSpec, draw_sample

    settings = get_settings()
    _refuse_redraw(settings.labels_dir, [p.name for p in SET_PLANS], force)
    reviews = pd.read_parquet(settings.processed_dir / "reviews.parquet")
    guideline = load_guideline()
    for plan in SET_PLANS:
        spec = SampleSpec(
            split=plan.split,
            n_total=plan.n_total,
            enriched_share=ENRICHED_SHARE,
            seed=settings.seed + plan.seed_offset,
        )
        sample = draw_sample(reviews, spec)
        aset = write_set(
            sample,
            plan.name,
            settings.labels_dir,
            guideline,
            batch_size=batch_size,
        )
        typer.echo(
            f"{plan.name}: {len(sample)} reviews from "
            f"{sample['hotel_id'].nunique()} "
            f"hotels, {len(aset.batches)} batches"
        )


SET_SPLIT = {
    "gold_test": "test",
    "gold_dev": "val",
    "train": "train",
    "train_2": "train",
}
"""The data split each label set must draw its hotels from."""
PANEL = ("A", "B", "C")
HUMAN_AUDIT_SIZE = 100


def _agreement_markdown(rows: list[dict[str, object]]) -> str:
    lines = [
        "# Annotator agreement",
        "",
        "_Generated by `curator label merge`. Agreement between three LLM "
        "annotators is a consistency signal, not human inter-annotator "
        "agreement (ADR 004)._",
        "",
        "| Set | Label | Fleiss' kappa | Mean pairwise Cohen's kappa | "
        "Unanimous parts | Positive parts (majority) |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for r in rows:
        lines.append(
            f"| {r['set']} | {r['label']} | {r['fleiss_kappa']:.3f} | "
            f"{r['mean_pairwise_cohen_kappa']:.3f} | "
            f"{100 * float(str(r['unanimous_rate'])):.1f}% | "
            f"{r['positives_majority']} |"
        )
    return "\n".join(lines) + "\n"


@app.command("sample-extra")
def sample_extra_cmd(
    batch_size: int = typer.Option(100, help="Reviews per annotator prompt."),
    force: Force = False,
) -> None:
    """Draw the second training sample, disjoint from every existing set."""
    from hotel_curator.labeling.batches import write_set
    from hotel_curator.labeling.prompt import load_guideline
    from hotel_curator.labeling.sampling import SampleSpec, draw_sample

    settings = get_settings()
    _refuse_redraw(settings.labels_dir, [EXTRA_TRAIN.name], force)
    reviews = pd.read_parquet(settings.processed_dir / "reviews.parquet")
    taken: set[str] = set()
    for plan in SET_PLANS:
        sample = pd.read_parquet(
            settings.labels_dir / plan.name / "sample.parquet"
        )
        taken |= set(sample["review_id"])
    spec = SampleSpec(
        split=EXTRA_TRAIN.split,
        n_total=EXTRA_TRAIN.n_total,
        enriched_share=ENRICHED_SHARE,
        seed=settings.seed + EXTRA_TRAIN.seed_offset,
    )
    sample = draw_sample(reviews, spec, exclude=taken)
    aset = write_set(
        sample,
        EXTRA_TRAIN.name,
        settings.labels_dir,
        load_guideline(),
        batch_size=batch_size,
    )
    typer.echo(
        f"{EXTRA_TRAIN.name}: {len(sample)} reviews from "
        f"{sample['hotel_id'].nunique()} hotels, {len(aset.batches)} batches"
    )


@app.command("prompts")
def prompts_cmd() -> None:
    """Rebuild the panel prompt files from the committed samples.

    Every rebuilt prompt is checked against the SHA-256 in the set's
    ``index.json``, i.e. against what the annotators were given.
    """
    from hotel_curator.labeling.batches import rewrite_prompts
    from hotel_curator.labeling.prompt import load_guideline

    settings = get_settings()
    guideline = load_guideline()
    for name in [p.name for p in SET_PLANS] + [EXTRA_TRAIN.name]:
        set_dir = settings.labels_dir / name
        if (set_dir / "index.json").is_file():
            n = rewrite_prompts(set_dir, guideline)
            typer.echo(f"{name}: {n} prompts rebuilt, hashes match")


@app.command("merge")
def merge_cmd() -> None:
    """Merge panel answers into labels.parquet per set, with agreement.

    Gold reviews whose hotel no longer belongs to the gold set's split (after
    a split change) are moved into the training labels.
    """
    from hotel_curator.labeling.gold import human_audit_sheet

    settings = get_settings()
    hotels = pd.read_parquet(settings.processed_dir / "hotels.parquet")
    split_of = hotels.set_index("hotel_id")["split"]
    tables, agreement_rows = _merge_sets(settings.labels_dir, hotels, split_of)
    _move_regrouped_gold(tables, split_of)
    _check_splits(tables, split_of)
    _write_label_tables(tables)
    (settings.labels_dir / "agreement.json").write_text(
        json.dumps(agreement_rows, indent=1, default=float) + "\n"
    )
    (settings.home / "docs" / "labeling" / "AGREEMENT.md").write_text(
        _agreement_markdown(agreement_rows)
    )
    sample = pd.read_parquet(
        settings.labels_dir / "gold_test" / "sample.parquet"
    )
    human_audit_sheet(sample, n=HUMAN_AUDIT_SIZE, seed=settings.seed).to_csv(
        settings.labels_dir / "human_audit_template.csv", index=False
    )


def _sets_to_merge(labels_dir: Path) -> list[tuple[str, tuple[str, ...]]]:
    """Each label set with its annotators; ``train_2`` once answered."""
    sets: list[tuple[str, tuple[str, ...]]] = [
        ("gold_test", PANEL),
        ("gold_dev", PANEL),
        ("train", ("A",)),
    ]
    if (labels_dir / EXTRA_TRAIN.name / "answers" / "A.jsonl").is_file():
        sets.append((EXTRA_TRAIN.name, ("A",)))
    return sets


def _merge_sets(
    labels_dir: Path, hotels: pd.DataFrame, split_of: pd.Series
) -> tuple[dict[str, pd.DataFrame], list[dict[str, object]]]:
    """Label tables per set, and agreement over the reviews each set keeps."""
    from dataclasses import asdict

    from hotel_curator.labeling.gold import build_label_table, merge_set

    tables: dict[str, pd.DataFrame] = {}
    agreement_rows: list[dict[str, object]] = []
    for name, annotators in _sets_to_merge(labels_dir):
        sample = pd.read_parquet(labels_dir / name / "sample.parquet")
        stays = sample["hotel_id"].map(split_of) == SET_SPLIT[name]
        result = merge_set(
            labels_dir / name,
            annotators,
            agreement_reviews=set(sample.loc[stays, "review_id"]),
        )
        tables[name] = build_label_table(result.parts, hotels).assign(
            source=name
        )
        agreement_rows += [{"set": name, **asdict(a)} for a in result.agreement]
    return tables, agreement_rows


def _move_regrouped_gold(
    tables: dict[str, pd.DataFrame], split_of: pd.Series
) -> None:
    """Move gold parts whose hotel left the gold split.

    Parts of hotels now in the training split join ``train``; parts of
    hotels now in another evaluation split are dropped, never moved into a
    set that is scored against them.
    """
    for name in ("gold_test", "gold_dev"):
        table = tables[name]
        now = table["hotel_id"].map(split_of)
        to_train = now == "train"
        dropped = (now != SET_SPLIT[name]) & ~to_train
        if to_train.any():
            typer.echo(f"{name}: moving {int(to_train.sum())} parts to train")
            tables["train"] = pd.concat([tables["train"], table[to_train]])
        if dropped.any():
            typer.echo(f"{name}: dropping {int(dropped.sum())} parts")
        tables[name] = table[now == SET_SPLIT[name]]


def _check_splits(tables: dict[str, pd.DataFrame], split_of: pd.Series) -> None:
    """Every label table's hotels must belong to that set's split.

    Raises:
        ValueError: If a table has a hotel from another split.
    """
    for name, table in tables.items():
        wrong = table.loc[table["hotel_id"].map(split_of) != SET_SPLIT[name]]
        if len(wrong):
            raise ValueError(
                f"{name} has {wrong['hotel_id'].nunique()} hotels outside "
                f"the {SET_SPLIT[name]} split"
            )


def _write_label_tables(tables: dict[str, pd.DataFrame]) -> None:
    """Write each set's labels.parquet and the labels manifest."""
    from hotel_curator.data.manifest import file_record, new_manifest

    settings = get_settings()
    manifest = new_manifest("labels", settings.home)
    for name, table in tables.items():
        path = settings.labels_dir / name / "labels.parquet"
        table.reset_index(drop=True).to_parquet(path, index=False)
        manifest.outputs.append(file_record(path, settings.home, len(table)))
        typer.echo(
            f"{name}: {len(table)} parts, {table['review_id'].nunique()} "
            f"reviews, {table['hotel_id'].nunique()} hotels"
        )
    manifest.stats = {
        name: {
            "parts": len(t),
            "reviews": int(t["review_id"].nunique()),
            "positives": {lbl: int(t[lbl].sum()) for lbl in LABELS},
        }
        for name, t in tables.items()
    }
    manifest.write(settings.manifests_dir / "labels.json")


EXTERNAL_NOTE = """\
These reviews come from a different site and are NOT split into Liked and
Disliked parts. Each review's full text is in the "liked" field. Label it as
one undivided review: judge polarity from the words alone (rule 5: middling
words are decided by the surrounding words), put all codes in "liked", and
return "" for "disliked".
"""
EXTERNAL_SET = "tripadvisor_annotated"


def _external_dir() -> Path:
    return get_settings().data_dir / "external"


@app.command("external-prepare")
def external_prepare_cmd(
    batch_size: int = typer.Option(50, help="Reviews per annotator prompt."),
) -> None:
    """Fetch TripAdvisor Annotated (pinned) and write panel prompts.

    Everything goes to gitignored directories: the source licence is
    unverified, so its text is never committed.
    """
    from hotel_curator.data.build import fetch
    from hotel_curator.labeling.batches import write_set
    from hotel_curator.labeling.external import (
        TRIPADVISOR_ANNOTATED,
        load_reviews,
    )
    from hotel_curator.labeling.prompt import load_guideline

    settings = get_settings()
    paths = fetch(TRIPADVISOR_ANNOTATED, settings.raw_dir)
    reviews = load_reviews(paths)
    sample = pd.DataFrame(
        {
            "review_id": "ta_" + reviews["review_id"].str.replace(":", "_"),
            "hotel_id": reviews["hotel_id"],
            "liked_text": reviews["text"],
            "disliked_text": None,
            "stratum": "external",
            "sampling_weight": 1.0,
        }
    )
    aset = write_set(
        sample,
        EXTERNAL_SET,
        _external_dir(),
        load_guideline(),
        batch_size=batch_size,
        max_chars=10_000,
        extra_instructions=EXTERNAL_NOTE,
    )
    typer.echo(f"{len(sample)} reviews, {len(aset.batches)} batches")


@app.command("external-score")
def external_score_cmd() -> None:
    """Compare panel labels with the human labels; write aggregates only."""
    from hotel_curator.labeling.batches import read_set
    from hotel_curator.labeling.external import TRIPLE_FILES, load_reviews

    settings = get_settings()
    set_dir = _external_dir() / EXTERNAL_SET
    raw = settings.raw_dir / "tripadvisor_annotated"
    panel = _panel_majority(set_dir, set(read_set(set_dir).review_ids))
    # human_labels orders the triple set by the original review id.
    triple_order = [
        _external_id(r)
        for r in sorted(load_reviews([raw / TRIPLE_FILES[0]])["review_id"])
    ]
    report: dict[str, Any] = {"n_panel_reviews": len(panel)}
    for variant, implicit in (("explicit", False), ("explicit_implicit", True)):
        for key, value in _external_variant(
            raw, panel, triple_order, implicit=implicit
        ).items():
            report[f"{variant}_{key}"] = value
    out = settings.labels_dir / "external_check.json"
    out.write_text(json.dumps(report, indent=1, default=float) + "\n")
    doc = settings.home / "docs" / "labeling" / "EXTERNAL_CHECK.md"
    doc.write_text(_external_markdown(report))
    typer.echo(f"wrote {out} and {doc}")


def _external_id(review_id: str) -> str:
    return "ta_" + review_id.replace(":", "_")


def _panel_majority(set_dir: Path, ids: set[str]) -> dict[str, set[str]]:
    """Labels a majority of the panel annotators gave, per review.

    Reviews missing an annotator's answer are left out.
    """
    from hotel_curator.labeling.batches import load_answers

    votes: dict[str, list[set[str]]] = {i: [] for i in ids}
    for annotator in PANEL:
        parsed, _ = load_answers(
            set_dir / "answers" / f"{annotator}.jsonl", ids
        )
        for rid, (liked, disliked) in parsed.labels.items():
            votes[rid].append(liked | disliked)
    return {
        rid: {
            lbl
            for lbl in LABELS
            if sum(lbl in v for v in given) > len(PANEL) // 2
        }
        for rid, given in votes.items()
        if len(given) == len(PANEL)
    }


def _external_variant(
    raw: Path,
    panel: dict[str, set[str]],
    triple_order: list[str],
    *,
    implicit: bool,
) -> dict[str, Any]:
    """Human agreement, triple-set kappas and panel-vs-human for one variant.

    ``implicit`` counts the source's implied opinions as labels too.
    """
    from hotel_curator.labeling.agreement import fleiss_kappa_binary
    from hotel_curator.labeling.external import (
        EXTERNAL_LABELS,
        HUMAN_RATERS,
        TRIPLE_FILES,
        compare_label_sets,
        human_labels,
        load_reviews,
        review_labels,
        triple_set_kappas,
    )

    humans = human_labels([raw / f for f in TRIPLE_FILES], implicit=implicit)
    reviews = load_reviews(sorted(raw.glob("*.json")))
    reference = {
        _external_id(rid): review_labels(sl, implicit=implicit)
        for rid, sl in zip(
            reviews["review_id"], reviews["segment_labels"], strict=True
        )
    }
    majority = humans.sum(axis=1) > HUMAN_RATERS // 2
    for i, rid in enumerate(triple_order):
        reference[rid] = {
            lbl for k, lbl in enumerate(EXTERNAL_LABELS) if majority[i, k]
        }
    return {
        "human_fleiss_kappa": {
            lbl: fleiss_kappa_binary(humans[:, :, k])
            for k, lbl in enumerate(EXTERNAL_LABELS)
        },
        "triple_kappa": triple_set_kappas(
            humans,
            [panel.get(rid, set()) for rid in triple_order],
            EXTERNAL_LABELS,
        ),
        "panel_vs_human": compare_label_sets(panel, reference, EXTERNAL_LABELS),
    }


EXTERNAL_INTRO = [
    "# External check: the annotator panel versus people",
    "",
    "_Generated by `curator label external-score`. Only aggregates are "
    "committed; the source reviews have an unverified licence and stay "
    "in a gitignored directory._",
    "",
    "The v2 labels come from an LLM annotator panel (ADR 004). To see how "
    "the panel compares with people, the same panel and guideline "
    "labeled the 442 unique reviews of *TripAdvisor Annotated* "
    "(Marcheggiani and Titov), whose sentence-level aspect labels were "
    "made by human annotators. 73 of those reviews were labeled by three "
    "people each, which allows a like-for-like comparison: does the "
    "panel agree with each person about as well as the people agree with "
    "each other?",
    "",
    "Caveats: different site and decade, whole reviews instead of "
    "Liked/Disliked parts, and a different guideline (the source has no "
    "noise or wifi aspect, so 12 of the 16 labels are checked). Human "
    "labels include implied opinions (`ip`/`in` codes); the explicit-only "
    "variant is in `data/labels/external_check.json`.",
    "",
]


def _triple_section(triple: list[dict[str, Any]]) -> list[str]:
    closer = sum(
        r["panel_human_kappa"] >= r["human_human_kappa"] for r in triple
    )
    lines = [
        "## Like-for-like: 73 reviews with three human annotators",
        "",
        f"The panel's mean kappa with a person is at least the people's mean "
        f"kappa with each other on **{closer} of {len(triple)}** labels.",
        "",
        "| Label | Human positives (mean of 3) | Panel positives | "
        "Human-human kappa | Panel-human kappa |",
        "|---|---:|---:|---:|---:|",
    ]
    return lines + [
        f"| {r['label']} | {r['human_positives_mean']:.1f} | "
        f"{int(r['panel_positives'])} | {r['human_human_kappa']:.2f} | "
        f"{r['panel_human_kappa']:.2f} |"
        for r in triple
    ]


def _full_section(full: list[dict[str, Any]]) -> list[str]:
    lines = [
        "",
        "## All 442 reviews: panel versus the human reference",
        "",
        "Reference = the single human annotator, or the majority of three. "
        "Precision and recall treat the human reference as truth.",
        "",
        "| Label | Support | Precision | Recall | F1 | Cohen's kappa |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    return lines + [
        f"| {r['label']} | {r['support']} | {r['precision']:.2f} | "
        f"{r['recall']:.2f} | {r['f1']:.2f} | {r['cohen_kappa']:.2f} |"
        for r in full
    ]


def _span(rows: list[dict[str, Any]], key: str) -> str:
    values = [float(r[key]) for r in rows]
    return f"{min(values):.2f} to {max(values):.2f}"


def _reading_section(full: list[dict[str, Any]]) -> list[str]:
    praise = [r for r in full if r["label"].endswith("_positive")]
    complaints = [r for r in full if r["label"].endswith("_negative")]
    return [
        "",
        "## Reading",
        "",
        f"- Recall against people ranges from {_span(full, 'recall')}. "
        f"Precision is {_span(praise, 'precision')} on praise and "
        f"{_span(complaints, 'precision')} on complaints: the panel marks "
        "mild or passing complaints the original annotators left out. "
        "Complaint rates estimated from v2 labels therefore lean high in "
        "absolute terms; comparisons between hotels are affected less, to "
        "the extent the over-marking is similar across hotels (not "
        "measured).",
        "- These numbers are about the *labels*. Model quality is measured "
        "against the panel's gold sets in `docs/model/COMPARISON.md`.",
        "- A direct human audit of 100 v2 gold reviews is prepared for the "
        "owner (`docs/labeling/HUMAN_AUDIT.md`, docs/BLOCKERS.md B3).",
        "",
    ]


def _external_markdown(report: dict[str, Any]) -> str:
    """Aggregate-only write-up of the panel-versus-human check."""
    full = report["explicit_implicit_panel_vs_human"]
    return "\n".join(
        EXTERNAL_INTRO
        + _triple_section(report["explicit_implicit_triple_kappa"])
        + _full_section(full)
        + _reading_section(full)
    )


@app.command("audit-score")
def audit_score_cmd(
    path: Path | None = None,
) -> None:
    """Score a filled human audit sheet against the panel's gold-test labels.

    Fill ``liked_codes`` / ``disliked_codes`` with codes such as ``C+ S-``
    (``none`` for a part without labels; leave empty to skip a part); see
    ``docs/labeling/HUMAN_AUDIT.md``.
    """
    from hotel_curator.labeling.external import compare_label_sets
    from hotel_curator.taxonomy import parse_codes

    settings = get_settings()
    sheet_path = path or settings.labels_dir / "human_audit_template.csv"
    sheet = pd.read_csv(sheet_path, dtype=str, keep_default_na=False)
    gold = pd.read_parquet(settings.labels_dir / "gold_test" / "labels.parquet")
    panel = {
        (str(r.review_id), str(r.part)): {
            lbl for lbl in LABELS if getattr(r, lbl)
        }
        for r in gold.itertuples()
    }
    human: dict[tuple[str, str], set[str]] = {}
    for row in sheet.itertuples():
        for part in ("liked", "disliked"):
            codes = str(getattr(row, f"{part}_codes")).strip()
            key = (str(row.review_id), part)
            if not codes or key not in panel:
                continue
            human[key] = (
                set() if codes.lower() == "none" else parse_codes(codes)
            )
    if not human:
        typer.echo("No labelled parts yet; see docs/labeling/HUMAN_AUDIT.md")
        raise typer.Exit(code=1)
    rows = compare_label_sets(
        {f"{k[0]}:{k[1]}": v for k, v in panel.items()},
        {f"{k[0]}:{k[1]}": v for k, v in human.items()},
        LABELS,
    )
    out = settings.labels_dir / "human_audit_result.json"
    out.write_text(json.dumps({"parts": len(human), "labels": rows}, indent=1))
    typer.echo(f"{len(human)} labelled parts; wrote {out}")
