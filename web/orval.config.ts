import { defineConfig } from 'orval';

/**
 * Readable names for the FastAPI operation ids. An operation that is not in
 * this map fails generation, so a new endpoint is a deliberate change here.
 */
const OPERATION_NAMES: Record<string, string> = {
  healthz_healthz_get: 'getHealthz',
  readyz_readyz_get: 'getReadyz',
  analyze_v1_analyze_post: 'analyzeReview',
  cities_v1_cities_get: 'listCities',
  compare_v1_compare_get: 'compareHotels',
  list_hotels_v1_hotels_get: 'listHotels',
  get_hotel_v1_hotels__hotel_id__get: 'getHotel',
  meta_v1_meta_get: 'getMeta',
};

export default defineConfig({
  curator: {
    input: {
      target: './openapi.json',
    },
    output: {
      mode: 'split',
      target: './src/api/generated/endpoints.ts',
      schemas: './src/api/generated/model',
      client: 'react-query',
      httpClient: 'fetch',
      baseUrl: '/api',
      clean: true,
      override: {
        // The default header contains a pictograph; keep generated files plain text.
        header: (info) => [
          'Generated by orval from web/openapi.json. Do not edit by hand.',
          'Regenerate with: npm run generate:api',
          `${info.title} ${info.version}`,
        ],
        mutator: {
          path: './src/api/fetcher.ts',
          name: 'apiFetch',
        },
        fetch: {
          includeHttpResponseReturnType: false,
          arrayFormat: 'repeat',
        },
        query: {
          signal: true,
        },
        operationName: (operation) => {
          const id = operation.operationId ?? '';
          const name = OPERATION_NAMES[id];
          if (!name) {
            throw new Error(`No client name for operation "${id}"; add it to orval.config.ts`);
          }
          return name;
        },
      },
    },
  },
});
