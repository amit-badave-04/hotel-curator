/**
 * Writes public/THIRD-PARTY-NOTICES.txt: every package whose code the web
 * app's production bundle can include, with its version, its declared
 * licence and the licence texts it ships. That is the packages
 * package-lock.json does not mark as development-only, plus BUILD_PACKAGES.
 * Their licences (MIT, ISC, BSD, Apache-2.0) ask that the notice go with
 * every copy, and every visitor gets a copy of the bundle, whose minified
 * scripts keep no licence comments. Run `npm run notices` after changing
 * dependencies; test/public-files.test.ts fails while the committed file is
 * out of date, or when the app's code imports a package not listed here.
 * Listing a package the bundle tree-shakes away is harmless; missing one is
 * not.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const WEB = fileURLToPath(new URL('..', import.meta.url));
const OUTPUT = join(WEB, 'public', 'THIRD-PARTY-NOTICES.txt');
const LICENCE_FILE = /^(third[-_]party[-_])?(licen[cs]es?|copying|notices?)(\.|$|-)/i;
const NODE_MODULES = 'node_modules/';
const RULE = '-'.repeat(72);

/** Development packages whose own code the build writes into the bundle:
 * Tailwind CSS's base styles and theme, Vite's module preload helpers and
 * Rolldown's module interop helpers (derived from esbuild, whose notice is
 * in Rolldown's THIRD-PARTY-LICENSE). */
export const BUILD_PACKAGES: readonly string[] = ['rolldown', 'tailwindcss', 'vite'];
const BUILD_PATHS = new Set(BUILD_PACKAGES.map((name) => NODE_MODULES + name));

const HEADER = `Third-party software in the hotel-curator web app
=================================================

The web app's JavaScript and CSS include code from the packages below: the
production dependencies in web/package-lock.json and everything they depend
on, and the build tools whose own code the build adds (Tailwind CSS's base
styles, Vite's and Rolldown's module helpers). Each is listed with its
version, its declared licence and the licence text it ships. Generated by
web/scripts/third-party-notices.ts (npm run notices); do not edit by hand.

hotel-curator's own code is MIT-licensed, and its data and model come with
the terms in /NOTICE.txt. The API documentation page (/api/docs) uses
Swagger UI, whose licence and notice are served with it at
/api/docs-assets/LICENSE and /api/docs-assets/NOTICE.
`;

interface LockPackage {
  version?: string;
  license?: string;
  dev?: boolean;
  devOptional?: boolean;
}

export interface ShippedPackage {
  path: string;
  name: string;
  version: string;
  license: string;
}

const byName = (a: ShippedPackage, b: ShippedPackage) =>
  a.name === b.name ? (a.version < b.version ? -1 : 1) : a.name < b.name ? -1 : 1;

/** The packages of a lock file whose code can ship: those not marked
 * development-only, and BUILD_PACKAGES. One per name and version. */
export function shippedPackages(lock: { packages: Record<string, LockPackage> }): ShippedPackage[] {
  const found = new Map<string, ShippedPackage>();
  for (const [path, entry] of Object.entries(lock.packages)) {
    const devOnly = (entry.dev || entry.devOptional) && !BUILD_PATHS.has(path);
    if (path === '' || devOnly) continue;
    const name = path.slice(path.lastIndexOf(NODE_MODULES) + NODE_MODULES.length);
    const version = entry.version ?? 'unknown';
    const key = `${name}@${version}`;
    if (!found.has(key)) {
      found.set(key, { path, name, version, license: entry.license ?? 'not declared' });
    }
  }
  return [...found.values()].sort(byName);
}

/** Licence files under `directory` (not in nested packages), relative. */
function licenceFiles(directory: string, prefix = ''): string[] {
  const found: string[] = [];
  for (const entry of readdirSync(join(directory, prefix), { withFileTypes: true })) {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory() && entry.name !== 'node_modules') {
      found.push(...licenceFiles(directory, relative));
    } else if (entry.isFile() && LICENCE_FILE.test(entry.name)) {
      found.push(relative);
    }
  }
  return found;
}

/** The licence and notice texts a package ships: its own (or a note that it
 * has none), then those of code it vendors (victory-vendor's copies of d3),
 * each labelled with its path. */
function licenceTexts(root: string, pkg: ShippedPackage): string[] {
  const directory = join(root, pkg.path);
  const depth = (file: string) => file.split('/').length;
  const files = licenceFiles(directory).sort((a, b) => depth(a) - depth(b) || (a < b ? -1 : 1));
  const read = (file: string) =>
    readFileSync(join(directory, file), 'utf8').replace(/\r\n?/g, '\n').trimEnd();
  const own = files.filter((file) => depth(file) === 1).map(read);
  const vendored = files
    .filter((file) => depth(file) > 1)
    .map((file) => `[${file}]\n${read(file)}`);
  const none = `(The package ships no licence file of its own; its package.json declares ${pkg.license}.)`;
  return [...(own.length ? own : [none]), ...vendored];
}

function section(root: string, pkg: ShippedPackage): string {
  const body = licenceTexts(root, pkg).join('\n\n');
  return `${RULE}\n${pkg.name} ${pkg.version} (${pkg.license})\n${RULE}\n\n${body}\n`;
}

/** The whole notices file for the web app in `root` (default: this one). */
export function thirdPartyNotices(root: string = WEB): string {
  const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
  const sections = shippedPackages(lock).map((pkg) => section(root, pkg));
  return [HEADER, ...sections].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(OUTPUT, thirdPartyNotices());
  process.stdout.write(`wrote ${OUTPUT}\n`);
}
